import type { Schemas } from './api/schemas';

// docs/backend/analysis for flash cards (#132): the child's game as a pure state machine, so the
// play page only renders it. The deck is fixed when the game starts (GET /flash-cards/me/sets/
// {setId}/deck). Pass one visits every slot once; the child flips the card and answers "Knew it"
// or "Not yet". Every "Not yet" slot is then repeated once, in slot order, at the end. A repeat
// answer never adds a further repeat and never changes the first-pass result: the stars come from
// knewFirstTime, which is all the server looks at (the repeat answer is sent as repeatedAnswer so
// the server can see what the game held, and it ignores it).
export type DeckCard = Schemas['DeckCard'];
export type FinishFlashCardGameRequest = Schemas['FinishFlashCardGameRequest'];
export type FinishFlashCardGameResult = Schemas['FinishFlashCardGameResultRequest'];

export interface FlashCardGame {
  readonly gameId: string;
  readonly setId: string;
  readonly tierId: string;
  readonly cards: readonly DeckCard[];
  // Per slot: the first-pass answer, null until given.
  readonly firstPass: readonly (boolean | null)[];
  // Per slot: the repeat answer, null until given (or when the slot is not repeated).
  readonly repeats: readonly (boolean | null)[];
  // How many turns were taken: 0..cards.length is the first pass, the rest the repeats.
  readonly step: number;
  // The current card's answer side is showing.
  readonly revealed: boolean;
}

export type GamePass = 'first' | 'repeat';

export interface CurrentCard {
  readonly slot: number;
  readonly card: DeckCard;
  readonly pass: GamePass;
  readonly revealed: boolean;
}

// gameId is generated by the caller when the game starts (crypto.randomUUID()) and reused by every
// retry of finishing it; the server tells a replay from a new game by it.
export function createGame(
  gameId: string,
  setId: string,
  tierId: string,
  cards: readonly DeckCard[],
): FlashCardGame {
  return {
    gameId,
    setId,
    tierId,
    cards,
    firstPass: cards.map(() => null),
    repeats: cards.map(() => null),
    step: 0,
    revealed: false,
  };
}

// The slots played again after the first pass: the ones answered "Not yet", in slot order. Empty
// until the first pass is over, because only then are all the answers in.
function repeatSlots(game: FlashCardGame): number[] {
  if (game.step < game.cards.length) {
    return [];
  }

  return game.firstPass.flatMap((knew, slot) => (knew === false ? [slot] : []));
}

export function isFinished(game: FlashCardGame): boolean {
  const total = game.cards.length;

  return game.step >= total && game.step - total >= repeatSlots(game).length;
}

export function current(game: FlashCardGame): CurrentCard | null {
  if (isFinished(game)) {
    return null;
  }

  const total = game.cards.length;
  const inFirstPass = game.step < total;
  const slot = inFirstPass ? game.step : (repeatSlots(game)[game.step - total] ?? -1);
  const card = game.cards[slot];

  return card === undefined
    ? null
    : { slot, card, pass: inFirstPass ? 'first' : 'repeat', revealed: game.revealed };
}

// Shows the answer side. Flipping again, or a finished game, changes nothing.
export function flip(game: FlashCardGame): FlashCardGame {
  return game.revealed || isFinished(game) ? game : { ...game, revealed: true };
}

// Records the answer for the current card and moves on. The card has to be flipped first, so a
// stray tap on the answer buttons cannot skip a question; before that, and once the game is over,
// it changes nothing. Only a first-pass answer decides whether the slot is repeated.
export function answer(game: FlashCardGame, knew: boolean): FlashCardGame {
  const now = current(game);

  if (now === null || !game.revealed) {
    return game;
  }

  const set = (answers: readonly (boolean | null)[]) =>
    answers.map((value, slot) => (slot === now.slot ? knew : value));

  return {
    ...game,
    firstPass: now.pass === 'first' ? set(game.firstPass) : game.firstPass,
    repeats: now.pass === 'repeat' ? set(game.repeats) : game.repeats,
    step: game.step + 1,
    revealed: false,
  };
}

// The per-slot results POST /flash-cards/me/games takes, only once the game is over (null before,
// so a half-played game is never sent). One result per slot, in slot order; repeatedAnswer is set
// only for a repeated slot.
export function toResults(game: FlashCardGame): FinishFlashCardGameResult[] | null {
  if (!isFinished(game)) {
    return null;
  }

  return game.cards.map((card, slot) => {
    const result: FinishFlashCardGameResult = {
      slot,
      cardKey: card.key,
      knewFirstTime: game.firstPass[slot] === true,
    };
    const repeated = game.repeats[slot];

    return repeated === null || repeated === undefined
      ? result
      : { ...result, repeatedAnswer: repeated };
  });
}

// The whole request, or null while the game is still going.
export function toFinishRequest(game: FlashCardGame): FinishFlashCardGameRequest | null {
  const results = toResults(game);

  return results === null
    ? null
    : { gameId: game.gameId, setId: game.setId, tierId: game.tierId, results };
}
