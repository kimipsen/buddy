using System.Security.Claims;

using buddy.Common;
using buddy.Common.OpenApi;

using Microsoft.AspNetCore.Http.HttpResults;

using Wolverine;

namespace buddy.Features.FlashCards;

public static class FinishFlashCardGameEndpoint
{
    public static RouteGroupBuilder MapFinishFlashCardGame(this RouteGroupBuilder flashCards)
    {
        flashCards.MapPost("/me/games", async Task<Results<Ok<FinishFlashCardGameResponse>, NotFound, BadRequest<ErrorEnvelope>, UnprocessableEntity<ErrorEnvelope>>> (
            ClaimsPrincipal principal,
            FinishFlashCardGameRequest request,
            IMessageBus bus,
            HttpContext httpContext,
            CancellationToken cancellationToken) =>
        {
            var command = FinishFlashCardGame.FromClaims(
                principal,
                request.GameId,
                new FlashCardSetId(request.SetId),
                new FlashCardTierId(request.TierId),
                [.. (request.Results ?? []).Select(r => new FinishFlashCardGameResult(r.Slot, r.CardKey ?? "", r.KnewFirstTime, r.RepeatedAnswer, r.Question, r.Answer))]);

            var result = await bus.InvokeAsync<FinishFlashCardGameOutcome>(command, cancellationToken);

            return result switch
            {
                FinishFlashCardGameOutcome.Success(var finished) => TypedResults.Ok(new FinishFlashCardGameResponse(
                    finished.Stars,
                    finished.TotalStars,
                    FlashCardGameResponse.From(finished.Game))),
                FinishFlashCardGameOutcome.NotFound => TypedResults.NotFound(),
                FinishFlashCardGameOutcome.Validation(var problem) => TypedResults.BadRequest(problem.ToEnvelope(httpContext)),
                FinishFlashCardGameOutcome.GameIdReused => TypedResults.UnprocessableEntity(new ErrorEnvelope(
                    FinishFlashCardGameOutcome.GameIdReusedCode,
                    "That game id already belongs to a different game.",
                    new Dictionary<string, string[]>(),
                    httpContext.TraceIdentifier)),
                FinishFlashCardGameOutcome.GameNoLongerAvailable => TypedResults.UnprocessableEntity(new ErrorEnvelope(
                    FinishFlashCardGameOutcome.GameNoLongerAvailableCode,
                    "This set or game length is no longer available for the child.",
                    new Dictionary<string, string[]>(),
                    httpContext.TraceIdentifier)),
            };
        })
        .ProducesErrorCode(
            StatusCodes.Status422UnprocessableEntity,
            FinishFlashCardGameOutcome.GameIdReusedCode,
            FinishFlashCardGameOutcome.GameNoLongerAvailableCode)
        .WithName("FinishFlashCardGame");

        return flashCards;
    }
}

// GameId is generated by the client when the game starts and reused by any retry; the
// Idempotency-Key is separate and new per call. The star value is never part of the request.
public sealed record FinishFlashCardGameResultRequest(int Slot, string? CardKey, bool KnewFirstTime)
{
    public bool? RepeatedAnswer { get; init; }

    // Only used when the card no longer exists (see FinishFlashCardGameResult).
    public string? Question { get; init; }

    public string? Answer { get; init; }
}

public sealed record FinishFlashCardGameRequest(Guid GameId, Guid SetId, Guid TierId, IReadOnlyList<FinishFlashCardGameResultRequest>? Results);
